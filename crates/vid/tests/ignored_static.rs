use std::error::Error;

#[test]
fn vid_ignores_static_png() -> Result<(), Box<dyn Error>> {
    // Minimal 1x1 PNG (valid PNG header + IHDR/IDAT/IEND chunks)
    const ONE_PNG: &[u8] = &[
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48,
        0x44, 0x52, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00,
        0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00, 0x0A, 0x49, 0x44, 0x41, 0x54, 0x78, 0x9C, 0x63,
        0x60, 0x00, 0x00, 0x00, 0x02, 0x00, 0x01, 0xE5, 0x27, 0x69, 0x8B, 0x00, 0x00, 0x00, 0x00,
        0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
    ];

    let tmp = tempfile::tempdir()?;
    let path = tmp.path().join("one.png");
    std::fs::write(&path, ONE_PNG)?;

    let config = shared_utils::conversion_types::ConversionConfig::default();

    // Call into vid's public API
    let out = vid::auto_convert_with_cache(&path, &config, None)?;

    assert!(out.ignored, "expected output to be ignored: {:?}", out);
    assert_eq!(out.strategy.target, shared_utils::conversion_types::TargetVideoFormat::Ignored);
    assert!(out.message.starts_with("IGNORED:"), "message = {}", out.message);

    Ok(())
}
